// Bundles the API for Vercel: vercel-entry.ts -> api/index.js (a single ES module).
// Third-party packages stay external (Vercel installs them); our own code is inlined.
import { build } from "esbuild";
import { rmSync } from "node:fs";

rmSync("api/index.ts", { force: true }); // a stale source entry would clash with api/index.js

const result = await build({
  entryPoints: ["vercel-entry.ts"],
  outfile: "api/index.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  packages: "external",
  logLevel: "warning",
  banner: { js: "/* oxlint-disable */\n// GENERATED by build-tools/bundle-api.mjs from vercel-entry.ts. Do not edit." },
  metafile: true,
});
const bytes = Object.values(result.metafile.outputs)[0].bytes;
console.log(`api/index.js written (${(bytes / 1024).toFixed(0)} KB)`);
